@dataclass(frozen=True)
class Target:
    key: str  # 英文标识，例如 "saturn"、"M42"
    name: str  # 中文名
    kind: str  # 太阳 / 月亮 / 行星 / 恒星 / 双星 / 星云 / 星系 / 星团
    story: str  # 讲给孩子听的一段话
    ra: float | None = None  # 赤经（度），太阳系天体为 None
    dec: float | None = None  # 赤纬（度）
    magnitude: float | None = None  # 星等，越小越亮
    aliases: tuple[str, ...] = ()

    @property
    def solar_system(self) -> bool:
        return self.ra is None


def _ra(h: float, m: float, s: float = 0.0) -> float:
    return (h + m / 60 + s / 3600) * 15


def _dec(d: float, m: float, s: float = 0.0) -> float:
    sign = -1 if d < 0 else 1
    return sign * (abs(d) + m / 60 + s / 3600)


