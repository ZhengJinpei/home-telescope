ALL_TARGETS: list[Target] = SOLAR_SYSTEM + STARS + DOUBLE_STARS + DEEP_SKY


def find(query: str) -> Target:
    """按中文名、英文标识或别名查找目标，不区分大小写。"""
    q = query.strip().lower().replace(" ", "")
    for t in ALL_TARGETS:
        names = [t.key.lower(), t.name.lower(), *(a.lower() for a in t.aliases)]
        if q in names:
            return t
    # 允许 "m 42"、"m042" 这类写法
    if q.startswith("m") and q[1:].isdigit() and q != f"m{int(q[1:])}":
        return find(f"M{int(q[1:])}")
    raise KeyError(f"找不到目标“{query}”，可以用 `python -m telescope list` 查看全部目标")
